function generateHistory(baseLevel: number, basePercent: number, baseRain: number) {
  const points = [];
  const hours = [24, 20, 16, 12, 8, 4, 0];
  for (let i = 0; i < hours.length; i++) {
    const h = hours[i];
    const trend = (hours.length - 1 - i) * 0.04;
    const timeLabel = h === 0 ? 'ปัจจุบัน' : `${h} ชม.ที่แล้ว`;
    points.push({
      time: timeLabel,
      levelMsl: Number((baseLevel - trend + (Math.sin(i) * 0.05)).toFixed(2)),
      percent: Math.min(100, Math.max(10, Math.round(basePercent - trend * 4))),
      rainfall: Math.max(0, Math.round(baseRain * (0.4 + (i / hours.length) * 0.6))),
    });
  }
  return points;
}

